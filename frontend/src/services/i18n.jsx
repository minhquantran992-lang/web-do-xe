export const translate = (key, forcedLang) => {
  const k = String(key || '').trim();
  const stored =
    typeof localStorage === 'undefined' ? '' : String(localStorage.getItem(STORAGE_KEY) || '').trim().toLowerCase();
  const lang = forcedLang || stored;
  const resolvedLang = lang === 'en' || lang === 'vi' ? lang : 'vi';
  return DICT[resolvedLang]?.[k] || DICT.en?.[k] || String(k);
};

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(() => {
    try {
      const saved = String(localStorage.getItem(STORAGE_KEY) || '').trim().toLowerCase();
      if (saved === 'en' || saved === 'vi') return saved;
    } catch {}
    return 'vi';
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  useEffect(() => {
    try {
      if (typeof document !== 'undefined') document.documentElement.lang = lang;
    } catch {}
  }, [lang]);

  const api = useMemo(() => {
    const t = (key) => DICT[lang]?.[key] || DICT.en?.[key] || String(key);
    const toggle = () => setLang((p) => (p === 'vi' ? 'en' : 'vi'));
    const set = (next) => setLang(next === 'en' ? 'en' : 'vi');
    return { lang, t, toggle, set };
  }, [lang]);

  return <LanguageContext.Provider value={api}>{children}</LanguageContext.Provider>;
};

export const useI18n = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useI18n must be used inside LanguageProvider');
  return ctx;
};
